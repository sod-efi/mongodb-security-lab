/*
 * Builds a single self-contained HTML report (no external assets, works
 * offline). Renders the cluster as an interactive SVG graph coloured by
 * severity, with a Before/After toggle when two runs are supplied so the map
 * visibly flips from red to green after hardening.
 *
 * buildHtml({ before, after? }) -> HTML string
 * `before` / `after` are the JSON objects returned by assess().
 */
export function buildHtml({ before, after = null }) {
  const data = JSON.stringify({ before, after });
  // The page script below uses NO backticks and NO ${...} so it can live inside
  // this template literal safely.
  const page = [
"(function(){",
"  var DATA = window.__DATA__;",
"  var SEVIDX = {CRITICAL:0,HIGH:1,MEDIUM:2,LOW:3,INFO:4};",
"  var COLOR = {CRITICAL:'#c0392b',HIGH:'#e67e22',MEDIUM:'#d4ac0d',LOW:'#2980b9',INFO:'#27ae60',NONE:'#27ae60'};",
"  var view = DATA.after ? 'before' : 'before';",
"  function esc(s){return String(s==null?'':s).replace(/[&<>\"]/g,function(c){return{'&':'&amp;','<':'&lt;','>':'&gt;','\"':'&quot;'}[c];});}",
"  function worst(run,id){var w='NONE';run.findings.forEach(function(f){if(f.nodeId===id&&SEVIDX[f.severity]<(SEVIDX[w]===undefined?9:SEVIDX[w]))w=f.severity;});return w;}",
"  function layout(run){",
"    var incoming={};run.edges.forEach(function(e){incoming[e.to]=true;});",
"    var depth={},q=[];run.nodes.forEach(function(n){if(!incoming[n.id]){depth[n.id]=0;q.push(n.id);}});",
"    while(q.length){var id=q.shift();run.edges.forEach(function(e){if(e.from===id&&depth[e.to]===undefined){depth[e.to]=depth[id]+1;q.push(e.to);}});}",
"    var byD={};run.nodes.forEach(function(n){var d=depth[n.id]===undefined?0:depth[n.id];(byD[d]=byD[d]||[]).push(n);});",
"    var pos={};Object.keys(byD).forEach(function(d){byD[d].forEach(function(n,i){pos[n.id]={x:60+d*230,y:50+i*110};});});",
"    return pos;",
"  }",
"  function renderGraph(run){",
"    var pos=layout(run);var W=0,H=0;Object.keys(pos).forEach(function(k){W=Math.max(W,pos[k].x+180);H=Math.max(H,pos[k].y+90);});",
"    var s='<svg viewBox=\"0 0 '+(W+40)+' '+(Math.max(H,160)+20)+'\" width=\"100%\">';",
"    s+='<defs><marker id=\"arr\" markerWidth=\"10\" markerHeight=\"10\" refX=\"9\" refY=\"3\" orient=\"auto\"><path d=\"M0,0 L9,3 L0,6 Z\" fill=\"#888\"/></marker></defs>';",
"    run.edges.forEach(function(e){var a=pos[e.from],b=pos[e.to];if(!a||!b)return;var x1=a.x+170,y1=a.y+35,x2=b.x,y2=b.y+35;",
"      s+='<line x1=\"'+x1+'\" y1=\"'+y1+'\" x2=\"'+x2+'\" y2=\"'+y2+'\" stroke=\"#888\" stroke-width=\"1.5\" marker-end=\"url(#arr)\"/>';",
"      var mx=(x1+x2)/2,my=(y1+y2)/2-4;s+='<text x=\"'+mx+'\" y=\"'+my+'\" class=\"edge\">'+esc(e.reason)+'</text>';});",
"    run.nodes.forEach(function(n){var p=pos[n.id];var w=worst(run,n.id);var col=COLOR[w];",
"      var auth=n.authRequired===false?'NO AUTH':(n.accessCred?('cracked: '+n.accessCred.user):'auth required');",
"      s+='<g class=\"node\" data-id=\"'+esc(n.id)+'\" style=\"cursor:pointer\">';",
"      s+='<rect x=\"'+p.x+'\" y=\"'+p.y+'\" rx=\"9\" width=\"170\" height=\"70\" fill=\"#fff\" stroke=\"'+col+'\" stroke-width=\"3\"/>';",
"      s+='<rect x=\"'+p.x+'\" y=\"'+p.y+'\" rx=\"9\" width=\"170\" height=\"20\" fill=\"'+col+'\"/>';",
"      s+='<text x=\"'+(p.x+8)+'\" y=\"'+(p.y+14)+'\" class=\"nid\">'+esc(n.host+':'+n.port)+'</text>';",
"      s+='<text x=\"'+(p.x+8)+'\" y=\"'+(p.y+38)+'\" class=\"nmeta\">v'+esc(n.version||'?')+(n.setName?('  {'+esc(n.setName)+'}'):'')+'</text>';",
"      s+='<text x=\"'+(p.x+8)+'\" y=\"'+(p.y+56)+'\" class=\"nmeta\" fill=\"'+col+'\">'+esc(auth)+'</text>';",
"      s+='</g>';});",
"    s+='</svg>';return s;",
"  }",
"  function fixFirst(run){var order=run.findings.slice().sort(function(a,b){return SEVIDX[a.severity]-SEVIDX[b.severity];});var f=order.find(function(x){return x.severity==='CRITICAL'||x.severity==='HIGH';});return f?f.remediation:null;}",
"  function renderSummary(run){",
"    var s=run.summary;var crit=s.critical;var chip=crit>0?'<span class=\"chip bad\">COMPROMISED</span>':'<span class=\"chip good\">SECURE</span>';",
"    var h='<h2>'+chip+'</h2>';",
"    h+='<p class=\"k\">'+s.nodesDiscovered+' nodes · '+s.credentialsHarvested+' credentials harvested · '+s.findings+' findings ('+crit+' critical)</p>';",
"    var ff=fixFirst(run);if(ff)h+='<div class=\"fix\"><b>Fix this first:</b> '+esc(ff)+'</div>';",
"    if(run.credentials.length){h+='<h3>Harvested credentials</h3><table class=\"t\"><tr><th>user</th><th>password</th><th>found at</th></tr>';",
"      run.credentials.forEach(function(c){h+='<tr><td>'+esc(c.user)+'</td><td><code>'+esc(c.pass)+'</code></td><td>'+esc(c.foundAt)+'</td></tr>';});h+='</table>';}",
"    else{h+='<p class=\"muted\">No credentials harvested.</p>';}",
"    h+='<p class=\"muted\">Click any node for its data and findings.</p>';return h;",
"  }",
"  function renderNode(run,id){var n=run.nodes.find(function(x){return x.id===id;});if(!n)return renderSummary(run);",
"    var h='<h2>'+esc(n.id)+'</h2>';",
"    h+='<p class=\"k\">mongod '+esc(n.version||'?')+' · '+(n.authRequired===false?'no auth':'auth required')+(n.setName?(' · replica set '+esc(n.setName)):'')+'</p>';",
"    var dbs=n.databases||{};var dbk=Object.keys(dbs);",
"    if(dbk.length){h+='<h3>Data read</h3>';dbk.forEach(function(db){h+='<div class=\"db\"><b>'+esc(db)+'</b><ul>';Object.keys(dbs[db]).forEach(function(c){h+='<li>'+esc(c)+' <span class=\"muted\">('+dbs[db][c].count+' docs)</span></li>';});h+='</ul></div>';});}",
"    else{h+='<p class=\"muted\">No data read from this node.</p>';}",
"    var fs=run.findings.filter(function(f){return f.nodeId===id;});",
"    if(fs.length){h+='<h3>Findings</h3>';fs.sort(function(a,b){return SEVIDX[a.severity]-SEVIDX[b.severity];}).forEach(function(f){h+='<div class=\"f\"><span class=\"sev\" style=\"background:'+COLOR[f.severity]+'\">'+f.severity+'</span> <b>'+esc(f.title)+'</b><p>'+esc(f.detail)+'</p><p class=\"rem\">Fix: '+esc(f.remediation)+'</p></div>';});}",
"    h+='<p><a href=\"#\" id=\"back\">&larr; back to summary</a></p>';return h;",
"  }",
"  function renderFindings(run){var fs=run.findings.slice().sort(function(a,b){return SEVIDX[a.severity]-SEVIDX[b.severity];});",
"    if(!fs.length)return '<p class=\"muted\">No findings.</p>';var h='<table class=\"t\"><tr><th>sev</th><th>finding</th><th>node</th></tr>';",
"    fs.forEach(function(f){h+='<tr><td><span class=\"sev\" style=\"background:'+COLOR[f.severity]+'\">'+f.severity+'</span></td><td>'+esc(f.title)+'</td><td><code>'+esc(f.nodeId)+'</code></td></tr>';});return h+'</table>';}",
"  function paint(id){var run=DATA[view];",
"    document.getElementById('graph').innerHTML=renderGraph(run);",
"    document.getElementById('detail').innerHTML=id?renderNode(run,id):renderSummary(run);",
"    document.getElementById('findings').innerHTML=renderFindings(run);",
"    var back=document.getElementById('back');if(back)back.onclick=function(e){e.preventDefault();paint(null);};",
"    Array.prototype.forEach.call(document.querySelectorAll('.node'),function(g){g.onclick=function(){paint(g.getAttribute('data-id'));};});",
"    if(DATA.after){document.getElementById('bBefore').className=view==='before'?'active':'';document.getElementById('bAfter').className=view==='after'?'active':'';}",
"  }",
"  if(DATA.after){document.getElementById('bBefore').onclick=function(){view='before';paint(null);};document.getElementById('bAfter').onclick=function(){view='after';paint(null);};}",
"  paint(null);",
"})();",
  ].join("\n");

  const toggle = after
    ? '<div class="toggle"><button id="bBefore" class="active">Before hardening</button><button id="bAfter">After hardening</button></div>'
    : '';

  return [
'<!doctype html>',
'<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">',
'<title>MongoDB cluster assessment</title>',
'<style>',
':root{--bg:#f6f7f9;--card:#fff;--ink:#1c2430;--muted:#6b7684;--line:#e3e7ec;}',
'@media (prefers-color-scheme:dark){:root{--bg:#12151a;--card:#1b2029;--ink:#e8ecf1;--muted:#8a94a2;--line:#2a3340;}}',
'*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--ink);font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;padding:16px;}',
'header{max-width:1100px;margin:0 auto 12px;}h1{font-size:20px;margin:0 0 2px;}.sub{color:var(--muted);margin:0;}',
'.wrap{max-width:1100px;margin:0 auto;display:grid;grid-template-columns:1.4fr 1fr;gap:14px;}',
'@media (max-width:820px){.wrap{grid-template-columns:1fr;}}',
'.panel{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:14px;}',
'.toggle{max-width:1100px;margin:0 auto 12px;display:flex;gap:8px;}',
'.toggle button{padding:8px 14px;border:1px solid var(--line);background:var(--card);color:var(--ink);border-radius:999px;cursor:pointer;font-weight:600;}',
'.toggle button.active{background:var(--ink);color:var(--card);border-color:var(--ink);}',
'h2{font-size:16px;margin:0 0 6px;}h3{font-size:13px;text-transform:uppercase;letter-spacing:.04em;color:var(--muted);margin:16px 0 6px;}',
'.chip{display:inline-block;padding:3px 10px;border-radius:999px;color:#fff;font-size:13px;}.chip.bad{background:#c0392b;}.chip.good{background:#27ae60;}',
'.k{color:var(--muted);margin:4px 0 10px;}.muted{color:var(--muted);}',
'.fix{background:rgba(192,57,43,.08);border-left:3px solid #c0392b;padding:8px 10px;border-radius:6px;margin:8px 0;}',
'.t{width:100%;border-collapse:collapse;font-size:13px;}.t th,.t td{text-align:left;padding:5px 8px;border-bottom:1px solid var(--line);vertical-align:top;}',
'.sev{color:#fff;padding:1px 7px;border-radius:5px;font-size:11px;font-weight:700;}',
'.f{border:1px solid var(--line);border-radius:8px;padding:8px 10px;margin:8px 0;}.f p{margin:4px 0;}.rem{color:var(--muted);font-size:13px;}',
'.db{margin:4px 0;}.db ul{margin:3px 0 3px 18px;padding:0;}',
'code{background:rgba(127,127,127,.12);padding:1px 5px;border-radius:4px;font-size:12px;}',
'text.nid{font:700 12px monospace;fill:#fff;}text.nmeta{font:11px monospace;fill:var(--ink);}text.edge{font:10px sans-serif;fill:var(--muted);}',
'svg .node rect:first-child{transition:filter .2s;}svg .node:hover rect:first-child{filter:brightness(.97);}',
'footer{max-width:1100px;margin:14px auto 0;color:var(--muted);font-size:12px;}',
'</style></head><body>',
'<header><h1>MongoDB cluster assessment</h1><p class="sub">Authorized lab assessment &middot; full network &amp; database picture from a single entry point</p></header>',
toggle,
'<div class="wrap">',
'<div class="panel"><div id="graph"></div></div>',
'<div class="panel" id="detail"></div>',
'</div>',
'<div class="wrap" style="margin-top:14px;grid-template-columns:1fr;"><div class="panel"><h3>All findings</h3><div id="findings"></div></div></div>',
'<footer>Lab use only. Generated ' + new Date().toISOString() + '. Read-only assessment &mdash; no data was modified.</footer>',
'<script>window.__DATA__=' + data + ';</script>',
'<script>' + page + '</script>',
'</body></html>',
  ].join('\n');
}
